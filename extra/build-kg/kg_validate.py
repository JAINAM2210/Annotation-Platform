PROJECT_DIR = BASE_DIR.parent
DATA_DIR = PROJECT_DIR / "data"
DEFAULT_CANDIDATES_CSV = DATA_DIR / "relation_candidates.csv"
DEFAULT_SENTENCES_CSV = DATA_DIR / "sentence_index.csv"
DEFAULT_OUTPUT_DIR = DATA_DIR / "validated"

WINDOW_SIZE = 2
DEFAULT_THRESHOLD = 0.58

TOKEN_PATTERN = re.compile(r"[a-z0-9]+")
